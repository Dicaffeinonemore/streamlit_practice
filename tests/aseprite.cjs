const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const A = require('../src/animation/aseprite.js');
const data = JSON.parse(fs.readFileSync(path.join(__dirname, '../assets/aseprite/exports/tests/black-knight-basic-attack.json'), 'utf8'));
const animation = A.parse(data, { anchor: [67, 143] }), clip = animation.clips['basic-attack'];
assert.equal(animation.frames.length, 6);
assert.deepEqual(clip.frames.map(f => f.duration), [100, 80, 60, 90, 110, 160]);
assert.equal(clip.duration, 600);
assert.equal(clip.gameReady, false);
assert.equal(animation.image, 'black-knight-basic-attack.png');
assert.deepEqual(clip.frames[1].atlas, [166, 0, 166, 143]);
assert.deepEqual(clip.frames[0].anchor, [67, 143]);
const p = new A.AnimationPlayer(animation.clips);
assert(p.play('basic-attack'));
p.advance(99); assert.equal(p.index, 0);
p.advance(1); assert.equal(p.index, 1);
p.advance(80); assert.equal(p.index, 2);
p.advance(420); assert(p.ended); assert.equal(p.index, 5);
p.advance(3000); assert.equal(p.index, 5);
p.seek(2); assert.equal(p.index, 2); assert(!p.ended);
p.play('basic-attack', { loop: true }); p.advance(1260); assert.equal(p.index, 0);
assert.equal(A.frameAtProgress(clip, 1).index, 5);
assert.equal(A.frameAtProgress(clip, 1, true).index, 0);
assert(!p.play('missing'));
const changed = direction => ({ ...data, meta: { ...data.meta, frameTags: [{ name: 'test', from: 0, to: 2, direction }] } });
assert.deepEqual(A.parse(changed('reverse')).clips.test.frames.map(f => f.index), [2, 1, 0]);
assert.deepEqual(A.parse(changed('pingpong')).clips.test.frames.map(f => f.index), [0, 1, 2, 1]);
assert.deepEqual(A.parse(changed('pingpong_reverse')).clips.test.frames.map(f => f.index), [2, 1, 0, 1]);
assert.equal(A.parse({ ...data, frames: Object.fromEntries(data.frames.map((f, i) => [String(i), f])) }).frames.length, 6);
assert.throws(() => A.parse({ ...data, frames: [{ ...data.frames[0], duration: 0 }] }));
assert.throws(() => A.parse({ ...data, frames: [{ ...data.frames[0], rotated: true }] }));
const trimmed = A.parse({ frames: [{ ...data.frames[0], trimmed: true, spriteSourceSize: { x: 4, y: 7 } }] }, { anchor: [67, 143] });
assert.deepEqual(trimmed.frames[0].anchor, [63, 136]);
const calls = [];
const ctx = Object.fromEntries(['save','restore','translate','scale','drawImage'].map(name => [name, (...args) => calls.push([name, ...args])]));
ctx.globalAlpha = 1;
A.draw(ctx, {}, trimmed.frames[0], { x: 30, y: 40, face: -1, scale: .72 });
assert.deepEqual(calls.find(c => c[0] === 'scale'), ['scale', -.72, .72]);
assert.deepEqual(calls.find(c => c[0] === 'drawImage').slice(2), [0, 0, 166, 143, -63, -136, 166, 143]);
assert.equal(calls.at(-1)[0], 'restore');
console.log('PASS: real CLI JSON, frame durations/boundaries, tags/directions, one-shot/loop/seek, atlas/anchor/trim, Canvas draw');
