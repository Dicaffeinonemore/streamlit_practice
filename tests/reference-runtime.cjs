const assert = require('node:assert/strict');
require('../src/animation/player.js');
const { ReferenceCombatant } = require('../src/combat/reference-combat.js');
const { AnimationPlayer } = global.ReferenceAnimation;
const clip = (id,n,loop=false) => ({id,frames:Array.from({length:n},(_,i)=>({index:i})),fps:10,loop,gameReady:true});
const animations = {idle:clip('idle',2,true),walk:clip('walk',3,true),attack:clip('attack',7),hurt:clip('hurt',4),death:clip('death',5),missing:{id:'missing',frames:[],fps:10}};
const events=[];
const p=new AnimationPlayer(animations,{onFrame:i=>events.push(i),onComplete:()=>events.push('end')});
assert(p.play('death'));p.advance(499);assert.equal(p.ended,false);assert.equal(p.index,4);
p.advance(1);p.advance(1000);assert.deepEqual(events,[0,1,2,3,4,'end']);
assert(!p.play('missing'));assert.equal(p.clip.id,'death','Missing animation must not fallback');
const review=new AnimationPlayer({idle:{...animations.idle,gameReady:false}});
assert(!review.play('idle'));
const preview=new AnimationPlayer({idle:{...animations.idle,gameReady:false}},{preview:true});assert(preview.play('idle'));
const skill={id:'attack',name:'테스트 전용 공격',animation:'attack',enabled:true,balance:{damage:10,cooldownMs:1000},activeFrames:[2,3,5],hitboxes:[{x:10,y:-20,w:40,h:20}],lockMovement:true,lockActions:true};
const actor=new ReferenceCombatant({animations,skills:{attack:skill},hp:100});
const target={x:20,y:-10,w:10,h:10,hp:100};
assert(actor.useSkill('attack',[target]));assert.equal(actor.phase,'windup');
assert(!actor.move(10,0));assert(!actor.useSkill('attack'));
actor.update(199);assert.equal(target.hp,100);
actor.update(1);assert.equal(target.hp,90);assert.equal(actor.phase,'active');
for(let i=0;i<20;i++)actor.update(1);assert.equal(target.hp,90,'No damage per render tick');
actor.update(380);assert.equal(target.hp,80,'Skipped intermediate frames still deliver second strike');
assert.equal(actor.phase,'recovery');actor.update(100);assert.equal(actor.state,'idle');
assert(!actor.useSkill('attack'));actor.update(300);assert(actor.useSkill('attack',[target]));
actor.update(200);assert.equal(target.hp,70,'Hit groups reset on next cast');
actor.damage(5);actor.update(500);assert.equal(target.hp,70,'Hurt cancels outgoing hits');
actor.damage(100);assert.equal(actor.state,'death');actor.update(499);assert(!actor.finished);
actor.update(1);assert(actor.finished);assert(!actor.useSkill('attack'));assert(!actor.move(1,0));
const left=new ReferenceCombatant({animations,skills:{attack:skill},hp:100});left.face=-1;
const leftTarget={x:-30,y:-10,w:10,h:10,hp:100},rightTarget={x:20,y:-10,w:10,h:10,hp:100};
left.useSkill('attack',[leftTarget,rightTarget]);left.update(200);assert.equal(leftTarget.hp,90);assert.equal(rightTarget.hp,100);
const disabled=new ReferenceCombatant({animations,skills:{attack:{...skill,enabled:false}},hp:100});assert(!disabled.useSkill('attack'));
console.log('PASS: frame events, one-shot death, missing/review gates, hit timing, multi-hit windows, cooldown, action/movement locks, interruption, mirrored collision');
