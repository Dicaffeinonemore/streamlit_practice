"""Embed the supplied Barel MP3s unchanged for all game distributions."""
import base64
import hashlib
import json
import shutil
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
folder = root / 'assets/sfx/barel'
folder.mkdir(parents=True, exist_ok=True)
names = {'swordHit': ('sword-hit.mp3', '바렐 검 타격.mp3'),
         'barelWave': ('wave.mp3', '바렐 장풍 공격.mp3'),
         'barelFinalHit': ('special-final-hit.mp3', '흑월참 마지막 일격.mp3'),
         'hurt': ('hurt.mp3', '피격 사운드.mp3'),
         'barelSlam': ('p-h-impact.mp3', 'p키 h키 사운드.mp3'),
         'barelCombo': ('special-combo.mp3', '흑월참 콤보 사운드.mp3')}
payload = {}
for key, (name, original) in names.items():
    target = folder / name
    if len(sys.argv) > 1:
        shutil.copyfile(Path(sys.argv[1]) / original, target)
    raw = target.read_bytes()
    payload[key] = 'data:audio/mpeg;base64,' + base64.b64encode(raw).decode('ascii')
    print(name, len(raw), hashlib.sha256(raw).hexdigest())
(root / 'barel-sfx.js').write_text(
    '// Generated by tools/build-barel-sfx.py; original MP3 bytes.\n'
    + 'window.BAREL_SFX_URLS = ' + json.dumps(payload, separators=(',', ':')) + ';\n', encoding='utf-8')
