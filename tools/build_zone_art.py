"""Cut the fire / frost / abyss zone sheet into 24 animation frames per row and bundle them for local and Streamlit play.

Sheet layout (2172x724): three rows (fire, frost, abyss), each a 24-frame eruption that flows left to right:
frames 1-4 warning sigil, 5-14 eruption, 15-24 dying embers. Frame numbers are printed under each row.
"""
from pathlib import Path
import base64
import io
import json
import sys
from PIL import Image
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
source = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / 'assets/effects/zones/지대 24프레임.png'
out = ROOT / 'assets/effects/zones'
out.mkdir(parents=True, exist_ok=True)

FRAMES = 24
# Centre x of each printed frame number (measured from the clean frost / abyss labels; fire's labels are smudged).
CENTERS = [55, 143, 238, 330, 421, 509, 602, 697, 792, 885, 974, 1059, 1143, 1230, 1319, 1409, 1498, 1587, 1675, 1763, 1851, 1942, 2030, 2119]
FW = 90        # frame width; neighbouring cells overlap slightly and are hidden by the feather
FEATHER = 18   # soft left/right edges so tiles blend when laid side by side in a zone
# Art rows above the printed numbers: (top, bottom)
ROWS = {'fire': (0, 226), 'frost': (250, 450), 'abyss': (472, 682)}

records, payload = {}, {}
with Image.open(source) as sheet:
    sheet = sheet.convert('RGBA')
    assert sheet.size == (2172, 724), sheet.size
    ramp = np.ones(FW, dtype=np.float32)
    ramp[:FEATHER] = np.linspace(0, 1, FEATHER, endpoint=False) ** 1.5
    ramp[-FEATHER:] = ramp[:FEATHER][::-1]
    for kind, (top, bottom) in ROWS.items():
        h = bottom - top
        atlas = Image.new('RGBA', (FW * FRAMES, h))
        for i, cx in enumerate(CENTERS):
            left = max(0, min(sheet.width - FW, cx - FW // 2))
            cell = np.array(sheet.crop((left, top, left + FW, bottom)), dtype=np.float32)
            cell[..., 3] *= ramp[None, :]
            atlas.paste(Image.fromarray(cell.round().astype(np.uint8), 'RGBA'), (i * FW, 0))
        # Ground band = brightest row of the sigil frames (the glowing floor ring).
        sigils = np.array(atlas.crop((0, 0, FW * 4, h)), dtype=np.float32)
        lum = (sigils[..., :3].sum(2) * sigils[..., 3] / 255).mean(1)
        ground = int(lum.argmax())
        atlas.save(out / f'{kind}.png')
        buf = io.BytesIO()
        atlas.save(buf, 'WEBP', quality=90, method=6)
        payload[kind] = 'data:image/webp;base64,' + base64.b64encode(buf.getvalue()).decode('ascii')
        records[kind] = dict(frames=FRAMES, fw=FW, feather=FEATHER, h=h, ground=ground)
        print(f'{kind}: {FRAMES} frames of {FW}x{h}, ground y {ground}')

(ROOT / 'zone-art.js').write_text("'use strict';\n// Generated by tools/build_zone_art.py - 24-frame fire / frost / abyss zone eruptions.\nconst ZONE_ART = " + json.dumps(records) +
    ';\nconst ZONE_IMAGES = Object.fromEntries(Object.entries(' + json.dumps(payload) +
    ').map(([k, src]) => { const im = new Image(); im.src = src; return [k, im]; }));\n', encoding='utf8')
print('Bundled zone frame atlases.')
