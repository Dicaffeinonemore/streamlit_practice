"""Embed the supplied six-frame-per-row sheet without altering its pixels."""
import base64
import hashlib
import json
import shutil
import sys
from pathlib import Path
from PIL import Image

root = Path(__file__).resolve().parents[1]
source = root / 'assets/effects/barel-combo/source.png'
if len(sys.argv) > 1:
    source.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(sys.argv[1], source)
with Image.open(source) as image:
    assert image.size == (1600, 900)
payload = {
    'image': 'data:image/png;base64,' + base64.b64encode(source.read_bytes()).decode('ascii'),
    'sha256': hashlib.sha256(source.read_bytes()).hexdigest(),
    # Gutters are not an exact 1600/6 grid; retain the tips of the widest cels.
    'columns': [0, 220, 490, 800, 1085, 1350, 1600],
    'centers': [133, 400, 667, 933, 1200, 1467],
    'rows': [0, 280, 570, 900],
    'anchorY': [174, 150, 145],
}
(root / 'barel-combo-fx-art.js').write_text(
    '// Generated by tools/build-barel-combo-fx.py; original PNG bytes.\n'
    + 'const BAREL_COMBO_FX_ART = ' + json.dumps(payload, separators=(',', ':')) + ';\n',
    encoding='utf-8',
)
print('Embedded supplied 1600x900 sheet:', payload['sha256'])
